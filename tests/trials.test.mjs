import assert from "node:assert/strict";
import { readFile } from "node:fs/promises";
import test from "node:test";
import { URL } from "node:url";
import ts from "typescript";

const root = new URL("../", import.meta.url);
const source = await readFile(new URL("app/trials.ts", root), "utf8");
const compiled = ts.transpileModule(source, {
  compilerOptions: { target: ts.ScriptTarget.ES2022, module: ts.ModuleKind.ESNext },
}).outputText;
const { DOT_TRIALS, generateBalancedTrials, seededRandom, makeDotCloud } = await import(`data:text/javascript,${encodeURIComponent(compiled)}`);

test("balances correct and advised sides in each of 1000 randomized sessions", () => {
  const snapshot = JSON.stringify(DOT_TRIALS);
  const orders = new Set();
  const orientations = new Set();
  for (let seed = 0; seed < 1000; seed += 1) {
    const trials = generateBalancedTrials(seededRandom(`session-${seed}`));
    assert.equal(trials.length, 6);
    assert.deepEqual(trials.map((trial) => trial.id).sort(), DOT_TRIALS.map((trial) => trial.id).sort());
    const correct = trials.filter((trial) => trial.correctChoice === trial.aiChoice);
    const errors = trials.filter((trial) => trial.correctChoice !== trial.aiChoice);
    assert.equal(correct.length, 4);
    assert.equal(errors.length, 2);
    for (const side of ["left", "right"]) {
      assert.equal(trials.filter((trial) => trial.correctChoice === side).length, 3);
      assert.equal(trials.filter((trial) => trial.aiChoice === side).length, 3);
      assert.equal(correct.filter((trial) => trial.aiChoice === side).length, 2);
      assert.equal(errors.filter((trial) => trial.aiChoice === side).length, 1);
      assert.equal(errors.filter((trial) => trial.correctChoice === side).length, 1);
    }
    orders.add(trials.map((trial) => trial.id).join());
    orientations.add([...trials].sort((a, b) => a.id.localeCompare(b.id)).map((trial) => trial.correctChoice).join());
  }
  assert.ok(orders.size > 100);
  assert.ok(orientations.size > 1);
  assert.equal(JSON.stringify(DOT_TRIALS), snapshot);
});

test("mirroring preserves item IDs, cloud geometry, count differences and item advice accuracy", () => {
  for (let seed = 0; seed < 30; seed += 1) {
    for (const trial of generateBalancedTrials(seededRandom(`mirror-${seed}`))) {
      const original = DOT_TRIALS.find((item) => item.id === trial.id);
      assert.equal(Math.abs(trial.leftCount - trial.rightCount), Math.abs(original.leftCount - original.rightCount));
      assert.equal(trial.correctChoice, trial.leftCount > trial.rightCount ? "left" : "right");
      assert.equal(trial.aiChoice === trial.correctChoice, original.aiChoice === original.correctChoice);
      const sourceLeft = trial.mirrored ? "right" : "left";
      const sourceRight = trial.mirrored ? "left" : "right";
      assert.equal(trial.leftCloudSeed, `${trial.id}-${sourceLeft}`);
      assert.equal(trial.rightCloudSeed, `${trial.id}-${sourceRight}`);
      assert.equal(trial.leftCount, original[`${sourceLeft}Count`]);
      assert.equal(trial.rightCount, original[`${sourceRight}Count`]);
      const cloud = makeDotCloud(trial.leftCount, trial.leftCloudSeed, trial.mirrored);
      const baseCloud = makeDotCloud(trial.leftCount, trial.leftCloudSeed, false);
      assert.equal((cloud.match(/data-dot=/g) ?? []).length, trial.leftCount);
      assert.equal(cloud, trial.mirrored ? baseCloud.replaceAll('style="left:', 'style="right:') : baseCloud);
    }
  }
});

test("discloses simulation before participation without revealing the accuracy schedule", async () => {
  const page = await readFile(new URL("app/page.tsx", root), "utf8");
  const consent = page.slice(page.indexOf('<section class="trial-card consent-card">'), page.indexOf('data: { phase: "consent" }'));
  const instructions = page.slice(page.indexOf('<section class="trial-card instruction-card">'), page.indexOf('data: { phase: "instructions" }'));
  const landing = page.slice(page.indexOf('<section className="hero-grid">'));
  for (const copy of [consent, instructions, landing]) {
    assert.match(copy, /simulated AI adviser/);
    assert.match(copy, /pre-programmed for research/);
    assert.match(copy, /not\s+generated by a live AI model/);
    assert.match(copy, /imperfect/);
    assert.doesNotMatch(copy, /four of|4\/6|two errors/i);
  }
  assert.doesNotMatch(landing, /Behavior before belief|Trust, before|implicit/i);
  assert.match(page, /stimulus_duration: 1200/);
  assert.match(page, /stimulus_mirrored: initial\.stimulus_mirrored/);
  assert.match(page, /dot_count_left: initial\.dot_count_left/);
  assert.match(page, /dot_count_right: initial\.dot_count_right/);
});
